// func expAVX2(dst, src *float32, n, mode int)
// mode 0: e^x; 1: 1 / (1 + e^-x); 2: x / (1 + e^-x). n is a multiple of 8.
TEXT ·expAVX2(SB), NOSPLIT, $0-32
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVQ n+16(FP), CX
	MOVQ mode+24(FP), DX
	VMOVUPS log2e<>(SB), Y8
	VMOVUPS c1<>(SB), Y9
	VMOVUPS c2<>(SB), Y10
	VMOVUPS half<>(SB), Y11
	VMOVUPS one<>(SB), Y12
	VMOVUPS hi<>(SB), Y13
	VMOVUPS lo<>(SB), Y14
	VMOVUPS signbit<>(SB), Y15
loop:
	VMOVUPS (SI), Y5        // x
	VMOVAPS Y5, Y0
	CMPQ DX, $0
	JE   exp
	VXORPS Y15, Y5, Y0      // -x
exp:
	VMINPS Y0, Y13, Y0
	VMAXPS Y0, Y14, Y0
	VMOVAPS Y0, Y1
	VFMADD213PS Y11, Y8, Y1 // x log2e + 0.5
	VROUNDPS $1, Y1, Y1     // n = floor
	VFNMADD231PS Y9, Y1, Y0 // r = x - n c1 - n c2
	VFNMADD231PS Y10, Y1, Y0
	VMOVUPS p0<>(SB), Y2
	VFMADD213PS p1<>(SB), Y0, Y2
	VFMADD213PS p2<>(SB), Y0, Y2
	VFMADD213PS p3<>(SB), Y0, Y2
	VFMADD213PS p4<>(SB), Y0, Y2
	VFMADD213PS p5<>(SB), Y0, Y2
	VMULPS Y0, Y0, Y3
	VFMADD213PS Y0, Y3, Y2  // p r^2 + r
	VADDPS Y12, Y2, Y2      // + 1
	VCVTPS2DQ Y1, Y4
	VPADDD i126<>(SB), Y4, Y4
	VPSLLD $23, Y4, Y4
	VADDPS Y2, Y2, Y2       // 2 y: 2^n as 2^(n-1) twice, so that n = 128 does not overflow
	VMULPS Y4, Y2, Y0       // e^x
	CMPQ DX, $0
	JE   store
	VADDPS Y12, Y0, Y0      // 1 + e^-x
	CMPQ DX, $1
	JE   sigmoid
	VDIVPS Y0, Y5, Y0       // x / (1 + e^-x)
	JMP  store
sigmoid:
	VDIVPS Y0, Y12, Y0      // 1 / (1 + e^-x)
store:
	VMOVUPS Y0, (DI)
	ADDQ $32, SI
	ADDQ $32, DI
	SUBQ $8, CX
	JNZ  loop
	VZEROUPPER
	RET

// func axpyAVX2(dst *float32, a float32, x *float32, n int)
TEXT ·axpyAVX2(SB), NOSPLIT, $0-32
	MOVQ dst+0(FP), DI
	VBROADCASTSS a+8(FP), Y15
	MOVQ x+16(FP), SI
	MOVQ n+24(FP), CX
loopa:
