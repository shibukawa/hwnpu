// func kernelAVX2(kc int, a, b, c *float32, ldc int)
// c (6 rows of 16, ldc floats apart) += a (kc x 6, packed) b (kc x 16, packed): twelve YMM
// accumulators, two of B and a broadcast of A a step.
TEXT ·kernelAVX2(SB), NOSPLIT, $0-40
	MOVQ kc+0(FP), CX
	MOVQ a+8(FP), SI
	MOVQ b+16(FP), DX
	MOVQ c+24(FP), DI
	MOVQ ldc+32(FP), R8
	SHLQ $2, R8
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7
	VXORPS Y8, Y8, Y8
	VXORPS Y9, Y9, Y9
	VXORPS Y10, Y10, Y10
	VXORPS Y11, Y11, Y11
	TESTQ CX, CX
	JE store
loop:
	VMOVUPS (DX), Y12
	VMOVUPS 32(DX), Y13
	VBROADCASTSS 0(SI), Y14
	VFMADD231PS Y12, Y14, Y0
	VFMADD231PS Y13, Y14, Y1
	VBROADCASTSS 4(SI), Y15
	VFMADD231PS Y12, Y15, Y2
	VFMADD231PS Y13, Y15, Y3
	VBROADCASTSS 8(SI), Y14
	VFMADD231PS Y12, Y14, Y4
	VFMADD231PS Y13, Y14, Y5
	VBROADCASTSS 12(SI), Y15
	VFMADD231PS Y12, Y15, Y6
	VFMADD231PS Y13, Y15, Y7
	VBROADCASTSS 16(SI), Y14
	VFMADD231PS Y12, Y14, Y8
	VFMADD231PS Y13, Y14, Y9
	VBROADCASTSS 20(SI), Y15
	VFMADD231PS Y12, Y15, Y10
	VFMADD231PS Y13, Y15, Y11
	ADDQ $24, SI
	ADDQ $64, DX
	DECQ CX
	JNZ loop
store:
	VADDPS (DI), Y0, Y0
	VMOVUPS Y0, (DI)
	VADDPS 32(DI), Y1, Y1
	VMOVUPS Y1, 32(DI)
	ADDQ R8, DI
	VADDPS (DI), Y2, Y2
	VMOVUPS Y2, (DI)
	VADDPS 32(DI), Y3, Y3
	VMOVUPS Y3, 32(DI)
	ADDQ R8, DI
	VADDPS (DI), Y4, Y4
	VMOVUPS Y4, (DI)
	VADDPS 32(DI), Y5, Y5
	VMOVUPS Y5, 32(DI)
	ADDQ R8, DI
	VADDPS (DI), Y6, Y6
	VMOVUPS Y6, (DI)
	VADDPS 32(DI), Y7, Y7
	VMOVUPS Y7, 32(DI)
	ADDQ R8, DI
	VADDPS (DI), Y8, Y8
	VMOVUPS Y8, (DI)
	VADDPS 32(DI), Y9, Y9
	VMOVUPS Y9, 32(DI)
	ADDQ R8, DI
	VADDPS (DI), Y10, Y10
	VMOVUPS Y10, (DI)
	VADDPS 32(DI), Y11, Y11
	VMOVUPS Y11, 32(DI)
	VZEROUPPER
	RET

// func kernelAVX512(kc int, a, b, c *float32, ldc int)
// c (12 rows of 16, ldc floats apart) += a (kc x 12, packed) b (kc x 16, packed): twelve ZMM
// accumulators, a ZMM of B a step and each row's A broadcast from memory into its FMA.
TEXT ·kernelAVX512(SB), NOSPLIT, $0-40
	MOVQ kc+0(FP), CX
	MOVQ a+8(FP), SI
	MOVQ b+16(FP), DX
	MOVQ c+24(FP), DI
	MOVQ ldc+32(FP), R8
	SHLQ $2, R8
	VPXORD Z0, Z0, Z0
	VPXORD Z1, Z1, Z1
	VPXORD Z2, Z2, Z2
	VPXORD Z3, Z3, Z3
	VPXORD Z4, Z4, Z4
	VPXORD Z5, Z5, Z5
	VPXORD Z6, Z6, Z6
	VPXORD Z7, Z7, Z7
	VPXORD Z8, Z8, Z8
	VPXORD Z9, Z9, Z9
	VPXORD Z10, Z10, Z10
	VPXORD Z11, Z11, Z11
	TESTQ CX, CX
	JE store512
loop512:
	VMOVUPS (DX), Z12
	VFMADD231PS.BCST 0(SI), Z12, Z0
	VFMADD231PS.BCST 4(SI), Z12, Z1
	VFMADD231PS.BCST 8(SI), Z12, Z2
	VFMADD231PS.BCST 12(SI), Z12, Z3
	VFMADD231PS.BCST 16(SI), Z12, Z4
	VFMADD231PS.BCST 20(SI), Z12, Z5
	VFMADD231PS.BCST 24(SI), Z12, Z6
	VFMADD231PS.BCST 28(SI), Z12, Z7
	VFMADD231PS.BCST 32(SI), Z12, Z8
	VFMADD231PS.BCST 36(SI), Z12, Z9
	VFMADD231PS.BCST 40(SI), Z12, Z10
	VFMADD231PS.BCST 44(SI), Z12, Z11
	ADDQ $48, SI
	ADDQ $64, DX
	DECQ CX
	JNZ loop512
store512:
	VADDPS (DI), Z0, Z0
	VMOVUPS Z0, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z1, Z1
	VMOVUPS Z1, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z2, Z2
	VMOVUPS Z2, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z3, Z3
	VMOVUPS Z3, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z4, Z4
	VMOVUPS Z4, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z5, Z5
	VMOVUPS Z5, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z6, Z6
	VMOVUPS Z6, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z7, Z7
	VMOVUPS Z7, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z8, Z8
	VMOVUPS Z8, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z9, Z9
	VMOVUPS Z9, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z10, Z10
	VMOVUPS Z10, (DI)
	ADDQ R8, DI
	VADDPS (DI), Z11, Z11
	VMOVUPS Z11, (DI)
	VZEROUPPER
	RET
